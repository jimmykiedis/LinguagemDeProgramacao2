    private void inserirPeça(java.awt.event.ActionEvent evt) {
        Peça peça = obterPeçaInformada();
        String mensagem_erro = null;

        if (peça != null)
            mensagem_erro = controlador.inserirPeça(peça);
        else
            mensagem_erro = "Algum atributo da peça não foi informado";

        if (mensagem_erro == null) {
            Peça visão = peça.getVisão();
            peças_cadastradasComboBox.addItem(visão);
            peças_cadastradasComboBox.setSelectedItem(visão);
        } else {
            informarErro(mensagem_erro);
        }
    }
    
    private void consultarPeça(java.awt.event.ActionEvent evt) {
        Peça visão = (Peça) peças_cadastradasComboBox.getSelectedItem();
        Peça peça = null;
        String mensagem_erro = null;

        if (visão != null) {
            peça = Peça.buscarPeça(visão.getCódigo());
            if (peça == null) mensagem_erro = "Peça não cadastrada";
        } else {
            mensagem_erro = "Nenhuma peça selecionada";
        }

        if (mensagem_erro == null) {
            códigoTextField.setText(peça.getCódigo() + "");
            nomeTextField.setText(peça.getNome());
            marcaComboBox.setSelectedItem(peça.getMarca());
            preçoTextField.setText(peça.getPreço() + "");
            encomendaCheckBox.setSelected(peça.isSobEncomenda());
        } else {
            informarErro(mensagem_erro);
        }
    }
    
    private Peça obterPeçaInformada() {
        String códigoTexto = códigoTextField.getText().trim();
        String nome = nomeTextField.getText().trim();
        String preçoTexto = preçoTextField.getText().trim();

        if (códigoTexto.isEmpty() || nome.isEmpty() || preçoTexto.isEmpty()) {
            return null;
        }

        Peça.Marca marca = (Peça.Marca) marcaComboBox.getSelectedItem();
        if (marca == null) {
            return null;
        }

        try {
            int código = Integer.parseInt(códigoTexto);
            double preço = Double.parseDouble(preçoTexto);
            boolean sob_encomenda = encomendaCheckBox.isSelected();

            return new Peça(código, nome, marca, preço, sob_encomenda);
        } catch (NumberFormatException exceção) {
            return null;
        }
    }
    
    private void informarErro (String mensagem) {
        JOptionPane.showMessageDialog (this, mensagem, "Erro", JOptionPane.ERROR_MESSAGE);
    }
    
    private void limparCampos(java.awt.event.ActionEvent evt) {
        códigoTextField.setText("");
        nomeTextField.setText("");
        marcaComboBox.setSelectedIndex(-1);
        preçoTextField.setText("");
        encomendaCheckBox.setSelected(false);
    }
    
